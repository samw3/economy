"""Generate a Lean module that states (and lets Lean's kernel check) the linter's claims.

The module instantiates the general model in `lean/EconomyModel` with the concrete economy:

* the market (goods and integer-scaled trade/craft actions) and either
  - `no_money_pump` from an exact shadow-price certificate, or
  - `pumpN_is_pump` for every money pump / duplication loop the linter reports;
* a *lucky* market (recipes with a success chance always succeed) with `income_ceiling` and
  `fastest_<item>` bounds that hold whatever the luck;
* encounter tables (win probabilities rounded to 1e-6) for every location and intended level,
  with lifespan claims mirroring the lifespan findings, and monotonicity chains.

Every theorem is closed by `decide +kernel`, i.e. checked by Lean's kernel with no extra axioms.
"""

from __future__ import annotations

import math
import re
from dataclasses import dataclass, field
from fractions import Fraction
from functools import reduce
from pathlib import Path

from ..analysis.combat import loadout
from ..analysis.market import build_market, grind_bounds, income_ceiling, loot_caps, start_holdings
from ..economy import Economy, Location
from ..lint.rules import Ctx

ODDS_DENOM = 10**6


@dataclass
class Theorem:
    name: str
    kind: str                 # no-pump | income-ceiling | pump | lifespan | monotone
    statement: str            # human description
    start: int = 0            # 1-based line range in the generated file
    end: int = 0
    meta: dict = field(default_factory=dict)


@dataclass
class LeanModule:
    name: str
    text: str
    theorems: list[Theorem]
    notes: list[str] = field(default_factory=list)


def module_name(source: str | None, eco: Economy) -> str:
    stem = Path(source).stem if source else eco.name
    parts = re.split(r"[^A-Za-z0-9]+", stem)
    name = "".join(p[:1].upper() + p[1:] for p in parts if p)
    if not name or not name[0].isalpha():
        name = "Economy" + name
    return name


class _Names:
    def __init__(self):
        self.used: set[str] = set()

    def get(self, *parts) -> str:
        base = "_".join(re.sub(r"[^A-Za-z0-9]+", "_", str(p)).strip("_") for p in parts if str(p))
        if not base or not base[0].isalpha():
            base = "x_" + base
        name, k = base, 2
        while name in self.used:
            name = f"{base}_{k}"
            k += 1
        self.used.add(name)
        return name


class _Writer:
    def __init__(self):
        self.lines: list[str] = []

    def w(self, s: str = ""):
        self.lines.extend(s.split("\n"))

    @property
    def line(self) -> int:
        return len(self.lines) + 1

    def text(self) -> str:
        return "\n".join(self.lines) + "\n"


def _frac_odds(p: float) -> Fraction:
    return Fraction(int(round(p * ODDS_DENOM)), ODDS_DENOM)


def encounter_table(eco: Economy, loc: Location, eff_level: float) -> list[tuple[int, Fraction]]:
    """(integer weight, rounded win probability) per variant, exactly as written to Lean."""
    weights: list[Fraction] = []
    for e in loc.encounters:
        n = e.lmax - e.lmin + 1
        w = Fraction(str(e.weight)) / n
        weights.extend([w] * n)
    den = reduce(math.lcm, (w.denominator for w in weights), 1)
    ints = [int(w * den) for w in weights]
    g = reduce(math.gcd, ints, 0) or 1
    ints = [x // g for x in ints]
    return [(w, _frac_odds(eco.odds(eff_level, v.level))) for w, v in zip(ints, loc.variants)]


def table_lifespan(t: list[tuple[int, Fraction]]) -> Fraction | None:
    weight = sum(w for w, _ in t)
    loss = sum(w * (1 - p) for w, p in t)
    if weight == 0 or loss == 0:
        return None
    return Fraction(weight) / loss


def _dominates(t2, t1) -> bool:
    return len(t1) == len(t2) and all(a[0] == b[0] and b[1] <= a[1] for a, b in zip(t2, t1))


def _c(text) -> str:
    """Make text safe inside a Lean comment (block comments nest on `/-` and close on `-/`)."""
    return str(text).replace("/-", "/ -").replace("-/", "- /")


def _rat(x: Fraction) -> str:
    return str(x.numerator) if x.denominator == 1 else f"{x.numerator}/{x.denominator}"


def generate(eco: Economy, ctx: Ctx, name: str, source: str | None = None) -> LeanModule:
    W = _Writer()
    N = _Names()
    thms: list[Theorem] = []
    notes: list[str] = []
    mk = ctx.market.market if ctx.market else None
    W.w("/-")
    W.w(f"  AUTO-GENERATED by `econ` from {_c(source or eco.name)} — do not edit by hand.")
    W.w(f"  Economy: {_c(eco.name)}")
    W.w("  Regenerate and check with: uv run econ prove <file>")
    W.w("  Every theorem below is closed by `decide +kernel`: Lean's kernel evaluates the concrete")
    W.w("  data and the general theorems in `EconomyModel` turn that into the stated property.")
    W.w("-/")
    W.w("import EconomyModel")
    W.w("")
    W.w(f"namespace Gen.{name}")
    W.w("open Econ")
    W.w("")

    # ---- market -------------------------------------------------------------------------
    if mk is not None:
        W.w("/-! ## Goods")
        for i, g in enumerate(mk.goods):
            if g in eco.currencies:
                cur = eco.currencies[g]
                base = min(cur.denominations, key=lambda d: d.value).name if cur.denominations else g
                kind = f"currency (unit: 1 {base})"
            else:
                kind = "item"
            prot = "protected" if g in mk.protected else "unprotected (worthless)"
            W.w(f"  {i:>3}  {_c(g):<24} {kind}, {prot}")
        W.w("-/")
        W.w("")
        W.w("/-! ## Market actions: net change in goods per action (negative = consumed).")
        W.w("Recipes with a success chance are scaled to whole numbers of expected outputs. -/")
        act_names = []
        for i, a in enumerate(mk.actions):
            scale, delta = a.int_delta()
            nm = N.get("act", i)
            act_names.append(nm)
            entries = ", ".join(f"({mk.index[g]}, {v})" for g, v in sorted(delta.items(), key=lambda t: mk.index[t[0]]))
            note = f" (×{scale} executions)" if scale != 1 else ""
            W.w(f"/-- {_c(a.id)}{note} -/")
            W.w(f"def {nm} : Bundle := [{entries}]")
        W.w("")
        W.w(f"def market : Market := {{ goods := {len(mk.goods)}, actions := [{', '.join(act_names)}] }}")
        W.w("")
        prot = [mk.index[g] for g in mk.goods if g in mk.protected]
        W.w("/-- Protected goods: currencies and items that can be sold, used in battle, or crafted into such. -/")
        W.w(f"def protectedGoods : List Nat := [{', '.join(map(str, prot))}]")
        W.w("def isProtected (g : Nat) : Bool := protectedGoods.contains g")
        W.w("")
        res = ctx.market
        caps = loot_caps(eco)
        if caps:
            W.w("/-- Everything a single faucet event (one kill, or one respawn) can hand out at once. -/")
            W.w("def lootCaps : List Loot := [")
            for k, (label, c) in enumerate(caps):
                entries = ", ".join(f"({mk.index[g]}, {v})" for g, v in sorted(c.items(), key=lambda t: mk.index[t[0]]))
                W.w(f"  {'' if k == 0 else ','}[{entries}]  -- {_c(label)}")
            W.w("]")
            W.w("")
        start = start_holdings(eco)
        W.w("/-- A new player's holdings (player.start). -/")
        W.w(f"def startList : List Int := [{', '.join(str(start.get(g, 0)) for g in mk.goods)}]")
        W.w("def startHoldings : Holdings := fun g => startList.getD g 0")
        W.w("")
        if res.prices is not None:
            den = reduce(math.lcm, (p.denominator for p in res.prices), 1)
            ints = [int(p * den) for p in res.prices]
            g = reduce(math.gcd, (x for x in ints if x), 0) or 1
            ints = [x // g for x in ints]
            W.w("/-- Shadow prices certifying the market (integer-scaled; see the goods table). -/")
            W.w(f"def shadowPrices : List Int := [{', '.join(map(str, ints))}]")
            W.w("def price (g : Nat) : Int := shadowPrices.getD g 0")
            W.w("")
            t = Theorem("no_money_pump", "no-pump",
                        "No combination of buying, selling, crafting and exchanging, repeated any number of times, "
                        "produces a protected good without consuming something"
                        + (" (recipes with a success chance count at their expected output)" if any(x.chancy for x in mk.actions) else "")
                        + ".")
            W.w("/-- **No money pump.** No combination of trades and recipes, repeated any number of times,")
            W.w("produces currency or a valuable item out of nothing (chancy recipes: in expectation). -/")
            t.start = W.line
            W.w("theorem no_money_pump : market.NoPump isProtected :=")
            W.w("  market.checkPrices_sound isProtected price (by decide +kernel)")
            t.end = W.line - 1
            thms.append(t)
            W.w("")
        else:
            first = None
            for k, p in enumerate(res.pumps):
                nm = f"pump{k + 1}"
                N.used.add(nm)
                desc = ", ".join(f"{t}× {mk.actions[i].id}" for t, i in p.combo)
                gain = ", ".join(f"+{eco.fmt_good(g, v)}" for g, v in p.net.items() if v > 0)
                # Lean actions for chancy recipes stand for `scale` executions: rescale multiplicities
                scales = {i: mk.actions[i].int_delta()[0] for _, i in p.combo}
                mult = reduce(math.lcm, (scales[i] // math.gcd(t, scales[i]) for t, i in p.combo), 1)
                combo = [(t * mult // scales[i], i) for t, i in p.combo]
                W.w(f"/-- Pump #{k + 1}: {_c(desc)} (net {_c(gain)}) -/")
                W.w(f"def {nm} : Combo := [{', '.join(f'({t}, {i})' for t, i in combo)}]")
                t = Theorem(f"{nm}_is_pump", "pump", f"{desc} is a pump (net {gain})", meta={"pump_index": k})
                t.start = W.line
                W.w(f"theorem {nm}_is_pump : market.IsPump isProtected {nm} :=")
                W.w(f"  market.checkPump_sound isProtected {nm} (by decide +kernel)")
                t.end = W.line - 1
                thms.append(t)
                W.w("")
                first = first or nm
            if first:
                t = Theorem("market_has_pump", "pump", "The market admits a pump.")
                t.start = W.line
                W.w("theorem market_has_pump : ¬ market.NoPump isProtected :=")
                W.w(f"  market.not_noPump_of_pump isProtected {first} {first}_is_pump")
                t.end = W.line - 1
                thms.append(t)
                W.w("")

        # ---- the lucky market: chancy recipes always succeed --------------------------------
        lucky = build_market(eco, lucky=True)
        if any(x.chancy for x in mk.actions):
            W.w("/-! ## Lucky market")
            W.w("The same actions, but every recipe with a success chance succeeds (failed crafts are just")
            W.w("losses). Claims about *any* luck — the income ceiling and fastest progression — use this market. -/")
            names = []
            for i, (ea, la) in enumerate(zip(mk.actions, lucky.actions)):
                if ea.delta == la.delta:
                    names.append(act_names[i])
                    continue
                nm = N.get("lucky_act", i)
                entries = ", ".join(f"({lucky.index[g]}, {int(v)})" for g, v in sorted(la.delta.items(), key=lambda t: lucky.index[t[0]]))
                W.w(f"/-- {_c(la.id)}, always succeeding -/")
                W.w(f"def {nm} : Bundle := [{entries}]")
                names.append(nm)
            W.w(f"def luckyMarket : Market := {{ goods := {len(lucky.goods)}, actions := [{', '.join(names)}] }}")
        else:
            W.w("/-- No recipe has a success chance, so luck cannot change any trade outcome. -/")
            W.w("def luckyMarket : Market := market")
        W.w("")

        # ---- income ceiling ---------------------------------------------------------------
        ic = income_ceiling(eco) if caps else None
        if ic is not None:
            den = reduce(math.lcm, (q.denominator for q in ic.prices), 1)
            cints = [int(q * den) for q in ic.prices]
            Dint = max(sum(cints[lucky.index[k]] * v for k, v in c.items()) for _, c in caps)
            per_event = float(ic.D)
            W.w("/-- A valuation of the lucky market (one base unit of the primary currency = "
                f"{den}) used for the income ceiling. -/")
            W.w(f"def ceilingPrices : List Int := [{', '.join(map(str, cints))}]")
            W.w(f"def maxLootValue : Int := {Dint}")
            W.w("")
            t = Theorem("income_ceiling", "income-ceiling",
                        f"after any sequence of trades and k kills/respawns, with any luck, net worth (valued with "
                        f"{eco.primary} at face value) grows by at most k × {eco.fmt_amount(eco.primary, per_event)}",
                        meta={"per_event": per_event})
            W.w("/-- **Income ceiling.** Whatever a player trades, crafts or rolls, every kill or respawn raises their")
            W.w(f"net worth by at most `maxLootValue` (= {_c(eco.fmt_amount(eco.primary, per_event))} of {_c(eco.primary)}). -/")
            t.start = W.line
            W.w("theorem income_ceiling : ∀ (evs : List Event) (h : Holdings),")
            W.w("    (∀ e ∈ evs, e.InRange luckyMarket.goods) → (∀ e ∈ evs, ∃ cap ∈ lootCaps, e.gained.Within cap) →")
            W.w("    Holdings.worth luckyMarket.goods (fun g => ceilingPrices.getD g 0) (luckyMarket.run h evs)")
            W.w("      ≤ Holdings.worth luckyMarket.goods (fun g => ceilingPrices.getD g 0) h")
            W.w("        + maxLootValue * (evs.countP Event.isGain : Int) :=")
            W.w("  luckyMarket.income_ceiling_of_valuation (fun g => ceilingPrices.getD g 0) lootCaps maxLootValue")
            W.w("    (by decide +kernel) (by decide +kernel)")
            t.end = W.line - 1
            thms.append(t)
            W.w("")
        elif caps:
            notes.append("no income ceiling: with lucky crafts (or a money pump) currency can be created without limit")

        # ---- fastest possible progression ----------------------------------------------
        bounds = grind_bounds(eco) if caps else {}
        chosen = sorted((b for b in bounds.values() if b.events >= 2), key=lambda b: -b.events)[:15]
        if chosen:
            W.w("/-! ## Fastest possible progression")
            W.w("For each item: a valuation of the lucky market proving that no strategy, however lucky, owns one")
            W.w("before this many faucet events (kills/respawns). -/")
            W.w("")
        for b in chosen:
            den = reduce(math.lcm, (q.denominator for q in b.prices), 1)
            pints = [int(q * den) for q in b.prices]
            g = reduce(math.gcd, (v for v in pints if v), 0) or 1
            pints = [v // g for v in pints]
            Dint = max(sum(pints[lucky.index[k]] * v for k, v in c.items()) for _, c in caps)
            ix = lucky.index[b.item]
            pn = N.get("grindPrices", b.item)
            th = N.get("fastest", b.item)
            W.w(f"def {pn} : List Int := [{', '.join(map(str, pints))}]")
            t = Theorem(th, "fastest",
                        f"no strategy owns {b.item} before {b.events} kills/respawns (from player.start, any luck)",
                        meta={"item": b.item, "events": b.events})
            W.w(f"/-- **Fastest {_c(b.item)}**: any player needs at least {b.events} loot/respawn events to own one. -/")
            t.start = W.line
            W.w(f"theorem {th} : ∀ evs : List Event, (∀ e ∈ evs, e.InRange luckyMarket.goods) →")
            W.w("    (∀ e ∈ evs, ∃ cap ∈ lootCaps, e.gained.Within cap) →")
            W.w("    (∀ g < luckyMarket.goods, 0 ≤ luckyMarket.run startHoldings evs g) →")
            W.w(f"    1 ≤ luckyMarket.run startHoldings evs {ix} → {b.events} ≤ evs.countP Event.isGain :=")
            W.w(f"  luckyMarket.grind_lower_bound (fun g => {pn}.getD g 0) lootCaps {Dint} {ix} startHoldings {b.events}")
            W.w("    (by decide +kernel)")
            t.end = W.line - 1
            thms.append(t)
            W.w("")

    # ---- lifespans ----------------------------------------------------------------------
    tgt = eco.targets.lifespan
    lo_t = Fraction(str(tgt[0])) if tgt and tgt[0] is not None else None
    hi_t = Fraction(str(tgt[1])) if tgt and tgt[1] is not None else None
    W.w("/-! ## Lifespans")
    W.w("Encounter tables list (weight, win probability) for every enemy × level a location can produce,")
    W.w(f"with win probabilities rounded to 1/{ODDS_DENOM:,}. `lifespan t.deathProb` is the expected number")
    W.w("of encounters per life (EconomyModel.Lifespan). -/")
    W.w("")
    for loc in eco.location_order():
        if not loc.level_range:
            continue
        a, b = loc.level_range
        b = min(b, eco.max_level)
        chains: dict[str, list[tuple[str, list]]] = {"geared": [], "naked": []}
        for lvl in range(a, b + 1):
            for kind in ("geared", "naked"):
                lo_ = loadout(eco, lvl, kind, ctx.obtainable)
                table = encounter_table(eco, loc, lvl + lo_.power)
                tn = N.get(loc.id, f"L{lvl}", kind)
                entries = ", ".join(f"({w}, {_rat(p)})" for w, p in table)
                W.w(f"/-- {_c(loc.id)} at level {lvl}, {_c(lo_.describe())} (effective level {lvl + lo_.power:g}) -/")
                W.w(f"def {tn} : EncounterTable := [{entries}]")
                chains[kind].append((tn, table))
                life = table_lifespan(table)
                if life is None:
                    notes.append(f"{tn}: death probability is 0 (immortal); no lifespan claim")
                    continue
                if kind == "geared" and lo_t is not None:
                    if life >= lo_t:
                        stmt, claim, verdict = f"({_rat(lo_t)} : Rat) ≤ lifespan {tn}.deathProb", f"≥ {float(lo_t):g}", "ok"
                    else:
                        stmt, claim, verdict = f"lifespan {tn}.deathProb < ({_rat(lo_t)} : Rat)", f"< {float(lo_t):g}", "short"
                elif kind == "naked" and hi_t is not None:
                    if life <= hi_t:
                        stmt, claim, verdict = f"lifespan {tn}.deathProb ≤ ({_rat(hi_t)} : Rat)", f"≤ {float(hi_t):g}", "ok"
                    else:
                        stmt, claim, verdict = f"({_rat(hi_t)} : Rat) < lifespan {tn}.deathProb", f"> {float(hi_t):g}", "long"
                else:
                    continue
                th = N.get(tn, "life")
                t = Theorem(th, "lifespan", f"{loc.id} level {lvl} ({kind}): lifespan {float(life):.2f} {claim}",
                            meta={"location": loc.id, "level": lvl, "loadout": kind, "verdict": verdict,
                                  "lifespan": float(life)})
                t.start = W.line
                W.w(f"theorem {th} : {stmt} := by decide +kernel")
                t.end = W.line - 1
                thms.append(t)
        for kind, chain in chains.items():
            if len(chain) < 2:
                continue
            if all(_dominates(t2, t1) for (_, t1), (_, t2) in zip(chain, chain[1:])):
                th = N.get(loc.id, kind, "monotone")
                t = Theorem(th, "monotone",
                            f"{loc.id} ({kind}): each level's table dominates the previous one, so lifespans never "
                            f"decrease as players level up (EncounterTable.dominates_lifespan)",
                            meta={"location": loc.id, "loadout": kind})
                W.w(f"/-- Levelling up in {_c(loc.id)} never lowers any win probability ({kind}). -/")
                t.start = W.line
                W.w(f"theorem {th} : EncounterTable.chainB [{', '.join(n for n, _ in chain)}] = true := by decide +kernel")
                t.end = W.line - 1
                thms.append(t)
        W.w("")
    W.w(f"end Gen.{name}")
    W.w("")
    main = [t.name for t in thms if t.kind in ("no-pump", "income-ceiling", "pump")][:3]
    for nm in main:
        W.w(f"#print axioms Gen.{name}.{nm}")
    return LeanModule(name, W.text(), thms, notes)
